export function findStockInUniverse(query) {
  if (!query) return null;
  const q = query.trim().toUpperCase();
  return OPTION_UNIVERSE.find(item => 
    item.ticker.toUpperCase() === q ||
    item.displayTicker.toUpperCase() === q ||
    item.ticker.replace(/\.(NS|BO)$/i, '').toUpperCase() === q ||
    item.name.toUpperCase().includes(q)
  );
}
